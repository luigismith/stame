def codepoint(ch):
    return ord(ch)


def scrivi(out_dir):
    cps = sorted(GLIFI, key=codepoint)
    righe = ['/* font_matrice.c — Matrice, il font a punti 5×7 di Stame (tools/matrice.py).',
             ' * File generato: non modificarlo a mano. */',
             '#include "font.h"', '',
             f'static const uint16_t CP[{len(cps)}] STAME_ROM = {{']
    for k in range(0, len(cps), 12):
        righe.append('    ' + ', '.join(f'0x{codepoint(c):04X}' for c in cps[k:k + 12]) + ',')
    righe.append('};')
    righe.append('')
    righe.append(f'static const gfx_mglyph_t G[{len(cps)}] STAME_ROM = {{')
    for ch in cps:
        rows = GLIFI[ch]
        w = len(rows[0])
        assert all(len(r) == w for r in rows), ch
        assert len(rows) in (7, 9), ch
        vals = []
        for r in range(9):
            v = 0
            if r < len(rows):
                for c, x in enumerate(rows[r]):
                    if x == '#':
                        v |= 1 << (w - 1 - c)
            vals.append(v)
        nome = ch if ch.isalnum() and ord(ch) < 128 else f'U+{codepoint(ch):04X}'
        righe.append(f'    {{ {w}, {{ ' + ', '.join(f'0x{v:02X}' for v in vals) + f' }} }},   /* {nome} */')
    righe.append('};')
    righe.append('')
    righe.append(f'const gfx_mfont_t GFX_MATRICE = {{ {len(cps)}, CP, G }};')
    righe.append('')
    percorso = os.path.join(out_dir, 'font_matrice.c')
    with open(percorso, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(righe))
    print(f'{percorso}: {len(cps)} glifi')


def mostra(testo):
    righe = [''] * 9
    for ch in testo:
        rows = GLIFI.get(ch, GLIFI['?'])
        w = len(rows[0])
        for r in range(9):
            riga = rows[r] if r < len(rows) else '.' * w
            righe[r] += riga.replace('.', ' ').replace('#', 'o') + ' '
    print('\n'.join(righe))


if __name__ == '__main__':
    if sys.argv[1] == '--mostra':
        mostra(sys.argv[2])
    else:
        scrivi(sys.argv[1])
